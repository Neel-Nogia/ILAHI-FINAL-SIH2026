// Helper to get unique districts per state
export function getDistrictsForState(state: 'Gujarat' | 'Rajasthan'): string[] {
  const set = new Set<string>();
  ALL_DESTINATIONS.filter(d => d.state === state).forEach(d => set.add(d.district));
  return Array.from(set).sort();
}

